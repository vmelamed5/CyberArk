<#
.Synopsis
   CHANGE CURRENT USER PASSWORD
   CREATED BY: Vadim Melamed, EMAIL: vmelamed5@gmail.com
.DESCRIPTION
   USE THIS FUNCTION TO CHANGE CURRENT USER PASSWORD IN EPM
.PARAMETER token
   HashTable of data containing various pieces of login information (EPMServer, LoginToken, HeaderType, etc).
   If -token is not passed, function will use last known hashtable generated by New-VPASEPMToken
.PARAMETER oldPassword
   Current password of the current user in EPM
.PARAMETER newPassword
   New password that will be set for the current user in EPM
.PARAMETER ConfirmNewPassword
   Confirm new password that will be set for the current user in EPM
.EXAMPLE
   $ChangePassword = Update-VPASEPMCurrentUserPassword -oldPassword {OLDPASSWORD VALUE} -newPassword {NEWPASSWORD VALUE} -ConfirmNewPassword {NEWPASSWORD VALUE}
.OUTPUTS
   $true if successful
   $false if failed
#>
function Update-VPASEPMCurrentUserPassword{
    [OutputType([bool])]
    [CmdletBinding()]
    Param(
        [Parameter(Mandatory=$true,ValueFromPipelineByPropertyName=$true,HelpMessage="Enter current password",Position=0)]
        [String]$oldPassword,

        [Parameter(Mandatory=$true,ValueFromPipelineByPropertyName=$true,HelpMessage="Enter new password",Position=1)]
        [String]$newPassword,

        [Parameter(Mandatory=$true,ValueFromPipelineByPropertyName=$true,HelpMessage="Confirm new password",Position=2)]
        [String]$ConfirmNewPassword,

        [Parameter(Mandatory=$false,ValueFromPipelineByPropertyName=$true,Position=3)]
        [hashtable]$token
    )

    Begin{
        $tokenval,$sessionval,$ManagerURL,$Header,$EPMServer,$EnableTextRecorder,$AuditTimeStamp,$HideWarnings,$AuthenticatedAs = Get-VPASEPMSession -token $token
        $CommandName = $MyInvocation.MyCommand.Name
        $log = Write-VPASEPMTextRecorder -inputval $CommandName -token $token -LogType COMMAND
    }
    Process{
        Write-Verbose "SUCCESSFULLY PARSED MANAGING URL VALUE"
        Write-Verbose "SUCCESSFULLY PARSED TOKEN VALUE"

        try{
            $params = @{
                oldPassword = $oldPassword
                newPassword = $newPassword
                newPasswordConfirm = $ConfirmNewPassword
            } | ConvertTo-Json
            $OutputParams = @{
                oldPassword = "{OldCredentials}"
                newPassword = "{NewCredentials}"
                newPasswordConfirm = "{NewCredentials}"
            }
            $log = Write-VPASEPMTextRecorder -inputval $OutputParams -token $token -LogType PARAMS

            $uri = "$ManagerURL/EPM/API/Users/Me/ChangePassword"
            Write-Verbose "SETTING URI: $uri"
            
            $log = Write-VPASEPMTextRecorder -inputval $uri -token $token -LogType URI
            $log = Write-VPASEPMTextRecorder -inputval "PATCH" -token $token -LogType METHOD
            write-verbose "MAKING API CALL TO CYBERARK"

            if($sessionval){
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Body $params -Method Patch -ContentType "application/json" -WebSession $sessionval
            }
            else{
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Body $params -Method Patch -ContentType "application/json"
            }

            if($response){
                $log = Write-VPASEPMTextRecorder -inputval "REST API COMMAND RETURNED: TRUE" -token $token -LogType MISC
                return $true
            }
            else{
                $log = Write-VPASEPMTextRecorder -inputval "FAILED TO CHANGE CURRENT USER PASSWORD" -token $token -LogType MISC
                $log = Write-VPASEPMTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
                return $false
            }
        }catch{
            $log = Write-VPASEPMTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASEPMTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "UNABLE TO CHANGE CURRENT USER PASSWORD"
            Write-VPASEPMOutput -str $_ -type E
            return $false
        }
    }
    End{
        $log = Write-VPASEPMTextRecorder -inputval $CommandName -token $token -LogType DIVIDER
    }
}
