function Get-VPASAccountCompliance{
    [OutputType('System.Object',[bool])]
    [CmdletBinding(DefaultParameterSetName='Set1')]
    Param(
        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$safe,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$platform,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$username,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [String]$address,

        [Parameter(Mandatory=$true,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true,HelpMessage="Unique AccountID that references the target account (for example: 3_12)")]
        [String]$AcctID,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Switch]$ExactMatch,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true)]
        [Switch]$ExportToCSV,

        [Parameter(Mandatory=$false,ParameterSetName='Set1',ValueFromPipelineByPropertyName=$true)]
        [Parameter(Mandatory=$false,ParameterSetName='Set2',ValueFromPipelineByPropertyName=$true)]
        [String]$CSVDirectory,

        [Parameter(Mandatory=$true,ParameterSetName='InputParameters',ValueFromPipelineByPropertyName=$true,HelpMessage="Hashtable of parameters required to make API call, refer to get-help -examples for valid inputs")]
        [hashtable]$InputParameters,

        [Parameter(Mandatory=$false,ValueFromPipelineByPropertyName=$true)]
        [hashtable]$token
    )

    Begin{
        $tokenval,$sessionval,$PVWA,$Header,$ISPSS,$IdentityURL,$EnableTextRecorder,$AuditTimeStamp,$NoSSL,$VaultVersion,$HideWarnings,$AuthenticatedAs,$SubDomain,$EnableTroubleshooting = Get-VPASSession -token $token
        $CommandName = $MyInvocation.MyCommand.Name
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType COMMAND
    }
    Process{
        try{
            if($PSCmdlet.ParameterSetName -eq "InputParameters"){
                $KeyHash = @{
                    set1 = @{
                        AcceptableKeys = @("safe","username","address","platform","ExactMatch","ExportToCSV","CSVDirectory")
                        MandatoryKeys = @()
                    }
                    set2 = @{
                        AcceptableKeys = @("AcctID","ExportToCSV","CSVDirectory")
                        MandatoryKeys = @()
                    }
                }
                $CheckSet = Test-VPASHashtableKeysHelper -InputHash $InputParameters -KeyHash $KeyHash

                if(!$CheckSet){
                    $log = Write-VPASTextRecorder -inputval "FAILED TO FIND TARGET PARAMETER SET" -token $token -LogType MISC
                    Write-Verbose "FAILED TO FIND TARGET PARAMETER SET"
                    Write-VPASOutput -str "FAILED TO FIND TARGET PARAMETER SET...VIEW EXAMPLES BELOW:" -type E
                    $examples = Write-VPASExampleHelper -CommandName $CommandName
                    return $false
                }
                else{
                    foreach($key in $InputParameters.Keys){
                        Set-Variable -Name $key -Value $InputParameters.$key
                    }
                }
            }
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "FAILED TO RETRIEVE ACCOUNTS"
            Write-VPASOutput -str $_ -type E
            return $false
        }

        try{
            $outputmatrix = @{
                value = @()
            }

            if($AcctID){
                Write-Verbose "ACCTID SUPPLIED, SKIPPING SEARCH QUERY"
                $params = @{
                    AcctID = $AcctID
                }
                write-verbose "ANALYZING ACCOUNTID: $AcctID"
                $data = Get-VPASAccountDetailsExtended -InputParameters $params
                $minihash = [ordered]@{
                    IsCompliant = $data.Compliance.IsCompliant
                    AccountID = $data.AccountID
                    Safe = $data.Details.SafeName
                    Address = $data.Details.RequiredProperties.Address
                    Username = $data.Details.RequiredProperties.Username
                    PlatformID = $data.Platform.PlatformID
                    Name = $data.Details.Name
                    LastUsedBy = $data.Details.LastUsedBy
                    LastUsedDate = $data.Details.LastUsedDate
                }
                $convertobj = [PSCustomObject]$minihash
                $outputmatrix.value += $convertobj
            }
            else{
                $APIParams = @{}
                if($safe){ $APIParams += @{safe = $safe} }
                if($platform){ $APIParams += @{platform = $platform} }
                if($username){ $APIParams += @{username = $username} }
                if($address){ $APIParams += @{address = $address} }
                if($ExactMatch){ $APIParams += @{ExactMatch = $ExactMatch} }

                $AllAccounts = Get-VPASAccountDetailsExtended -InputParameters $APIParams
                foreach($acct in $AllAccounts){
                    $minihash = [ordered]@{
                        IsCompliant = $acct.Compliance.IsCompliant
                        AccountID = $acct.AccountID
                        Safe = $acct.Details.SafeName
                        Address = $acct.Details.RequiredProperties.Address
                        Username = $acct.Details.RequiredProperties.Username
                        PlatformID = $acct.Platform.PlatformID
                        Name = $acct.Details.Name
                        LastUsedBy = $acct.Details.LastUsedBy
                        LastUsedDate = $acct.Details.LastUsedDate
                    }
                    $convertobj = [PSCustomObject]$minihash
                    $outputmatrix.value += $convertobj
                }
            }
            Write-Verbose "PARSING DATA FROM CYBERARK"
            Write-Verbose "RETURNING ACCOUNT COMPLIANCE DETAILS"
            if($ExportToCSV){
	            $runexport = Write-VPASExportCSV -Data $outputmatrix -CommandName $CommandName -CSVDirectory $CSVDirectory
            }
            return $outputmatrix
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "COULD NOT RETRIEVE ACCOUNT COMPLIANCE DETAILS"
            Write-VPASOutput -str $_ -type E
            return $false
        }
    }
    End{
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType DIVIDER
    }
}
