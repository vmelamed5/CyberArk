        SearchQuery = "domainadmin01"
		PlatformType = "Windows Server Local"|"Windows Desktop Local"|"Windows Domain"|"Unix"|"Unix SSH Key"|"AWS"|"AWS Access Keys"|"Azure Password Management"
		Privileged = "true"|"false"
        Enabled = "true"|"false"
        Confirm = $true|$false
