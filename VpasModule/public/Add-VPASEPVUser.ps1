            $businessaddr += @{workCountry = $WorkCountry}
        }

        if($businessaddr.Count -gt 0){
            Write-Verbose "ADDING BUSINESS ADDRESS TO PARAMS"
            $Params+= @{businessAddress = $businessaddr}
        }

        if([String]::IsNullOrEmpty($AuthenticationType)){
            Write-Verbose "NO AUTHENTICATION TYPE SPECIFIED, DEFAULT VALUE: AuthTypePass"
            $Params += @{authenticationMethod = @("AuthTypePass")}
            $AuthenticationType = "AuthTypePass"
        }
        else{
            Write-Verbose "PARSING AUTHENTICATION TYPE VALUE: $AuthenticationType"
            $Params += @{authenticationMethod = @($AuthenticationType)}
        }

        if($AuthenticationType -eq "AuthTypePass"){
            if([String]::IsNullOrEmpty($InitialPassword)){
                Write-VPASOutput -str "AuthTypePass REQUIRES AN INITIAL PASSWORD: " -type Y
                $InitialPassword = Read-Host
            }
        }

        if(![String]::IsNullOrEmpty($InitialPassword)){
            write-verbose "SETTING PASSWORD TO: $InitialPassword"
            $Params += @{initialPassword = $InitialPassword}
        }
        else{
            write-verbose "NO PASSWORD SET"
        }

        if(![String]::IsNullOrEmpty($DistinguishedName)){
            write-verbose "SETTING DISTINGUISHED NAME TO: $DistinguishedName"
            $Params += @{distinguishedName = $DistinguishedName}
        }
        else{
            write-verbose "NO DISTINGUISHED NAME SET"
        }

        write-verbose "SETTING PARAMETERS FOR API CALL"
        $log = Write-VPASTextRecorder -inputval $params -token $token -LogType PARAMS
        $Params = $Params | ConvertTo-Json

        try{

            Write-Verbose "MAKING API CALL TO CYBERARK"
            if($NoSSL){
                Write-Verbose "NO SSL ENABLED, USING HTTP INSTEAD OF HTTPS"
                $uri = "http://$PVWA/PasswordVault/api/Users"
            }
            else{
                Write-Verbose "SSL ENABLED BY DEFAULT, USING HTTPS"
                $uri = "https://$PVWA/PasswordVault/api/Users"
            }
            $log = Write-VPASTextRecorder -inputval $uri -token $token -LogType URI
            $log = Write-VPASTextRecorder -inputval "POST" -token $token -LogType METHOD

            if($sessionval){
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Method POST -Body $Params -ContentType "application/json" -WebSession $sessionval
                $APICounter += 1
            }
            else{
                $response = Invoke-RestMethod -Headers @{"Authorization"=$Header} -Uri $uri -Method POST -Body $Params -ContentType "application/json"
                $APICounter += 1
            }
            Write-Verbose "PARSING DATA FROM CYBERARK"
            Write-Verbose "OPERATION COMPLETED SUCCESSFULLY, RETURNING JSON OBJECT"
            $log = Write-VPASTextRecorder -inputval $response -token $token -LogType RETURN
            return $response
        }catch{
            $log = Write-VPASTextRecorder -inputval $_ -token $token -LogType ERROR
            $log = Write-VPASTextRecorder -inputval "REST API COMMAND RETURNED: FALSE" -token $token -LogType MISC
            Write-Verbose "UNABLE TO ADD EPVUSER"
            Write-VPASOutput -str $_ -type E
            return $false
        }
    }
    End{
        $log = Write-VPASTextRecorder -inputval $CommandName -token $token -LogType DIVIDER
        $token = Update-VPASSession -AddCounter $APICounter -InputToken $token
    }
