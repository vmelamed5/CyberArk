   Tag: Policies
   Since: v14.2.1
   Version: 5
   SelfHosted: FALSE
   PrivCloudStandard: FALSE
   SharedServices: TRUE
   SRS: FALSE
.PARAMETER token
   HashTable of data containing various pieces of login information (PVWA, LoginToken, HeaderType, etc).
   If -token is not passed, function will use last known hashtable generated by New-VPASToken
.PARAMETER PolicyID
   UniqueID of the target policy in SIA
.PARAMETER PolicyName
   Unique name of the target policy in SIA
.PARAMETER InputParameters
   HashTable of values containing the parameters required to make the API call
.EXAMPLE
   $PolicyDetails = Get-VPASSIAPolicyDetails -PolicyID {POLICY ID VALUE}
.EXAMPLE
   $PolicyDetails = Get-VPASSIAPolicyDetails -PolicyName {POLICY NAME VALUE}
.EXAMPLE
   $InputParameters = @{
        PolicyID = "lkjsdhf897-zxcv-asdf-7634-lksjd438754"
   }
   $PolicyDetails = Get-VPASSIAPolicyDetails -InputParameters $InputParameters
.EXAMPLE
   $InputParameters = @{
